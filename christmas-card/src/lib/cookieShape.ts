export function smilePoints(steps = 16): Pt[] {
  const { c, r, a0, a1 } = ICING.smile;
  const pts: Pt[] = [];
  for (let i = 0; i <= steps; i++) {
    const a = a0 + ((a1 - a0) * i) / steps;
    pts.push([c[0] + Math.cos(a) * r, c[1] + Math.sin(a) * r]);
  }
  return pts;
}

/** 나비넥타이의 두 날개(삼각형에 가까운 둥근 사각형) */
export function bowWings(): Pt[][] {
  const { c, w, h } = ICING.bow;
  const [x, y] = c;
  return [
    [
      [x - 3, y],
      [x - w, y - h],
      [x - w - 2, y],
      [x - w, y + h],
    ],
    [
      [x + 3, y],
      [x + w, y - h],
      [x + w + 2, y],
      [x + w, y + h],
    ],
  ];
}
